"""Extract the PRICE sheet template and the IE7981A01 annotations from the reference drawing PDF.

Run with pdfplumber and Pillow available (not part of the CAD kernel environment):

    python -I tools/extract_price_template.py vendor/IE7981A01_reference_drawing.pdf

Writes src/price_template.json (static lines, curves and text of the header strip, BOM
grid, title block, frame and footer, plus the anchors of every filled-in field),
src/ie7981a01_annotations.json (balloons, leaders, weld symbols, notes, photo callouts of
that one drawing) and assets/ (logo and the two product photos). All coordinates are PDF
points measured from the top-left corner of the A4 page (841.92 x 595.32).
"""
import json
import math
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import pdfplumber
from PIL import Image

HERE = Path(__file__).resolve().parent.parent
SRC, ASSETS = HERE / "src", HERE / "assets"
FONT = {"F1": "bold", "F2": "regular", "F3": "italic", "F4": "narrow"}

# Zones (x0, top, x1, bottom) holding the annotation primitives of this drawing.
WELD_ZONES = [(140, 268, 222, 296), (138, 350, 215, 380), (430, 344, 510, 372), (668, 348, 745, 372)]
NOTE_ZONES = [(670, 318, 752, 335),            # WELD TO PISTOL box and its shoulder line
              (560, 140, 640, 192),            # blowgun callout: text + shoulder
              (560, 445, 660, 480)]            # ejector callout: text + shoulder
LEADER_LINES_MIN = 28                           # balloon / weld leaders are longer than this


def r(v):
    return round(float(v), 2)


def region(o):
    t, x0 = o["top"], o["x0"]
    if t < 46:
        return "header"
    if t < 192 and x0 < 450:
        return "bom"
    if t >= 497:
        return "title"
    return "view"


def inside(o, zone):
    return o["x0"] >= zone[0] and o["x1"] <= zone[2] and o["top"] >= zone[1] and o["bottom"] <= zone[3]


def main(pdf_path):
    pdf_path = Path(pdf_path)
    with pdfplumber.open(pdf_path) as pdf:
        p = pdf.pages[0]
        H, W = p.height, p.width
        chars = p.chars

        def origin(c):
            return r(c["matrix"][4]), r(H - c["matrix"][5])

        # ---- static template geometry (header strip, frame, title block) ----
        seen, lines, curves = set(), [], []
        for o in p.lines:
            # the BOM grid (0.48 pt lines inside the table) is generated by the renderer, not stored
            q0 = o["pts"]
            frame = math.hypot(q0[1][0] - q0[0][0], q0[1][1] - q0[0][1]) > 400      # page frame edges
            if (region(o) == "view" and not frame) or (region(o) == "bom" and o["linewidth"] < 0.5):
                continue
            q = o["pts"]
            key = (r(q[0][0]), r(q[0][1]), r(q[1][0]), r(q[1][1]), r(o["linewidth"]))
            if key not in seen:
                seen.add(key)
                lines.append(list(key))
        for o in p.curves:
            if region(o) in ("header", "title"):
                curves.append({"pts": [[r(x), r(y)] for x, y in o["pts"]], "lw": r(o["linewidth"]), "fill": bool(o.get("fill"))})

        # ---- text ----
        words = p.extract_words(extra_attrs=["fontname", "size"], keep_blank_chars=True, x_tolerance=2.5, return_chars=True)
        texts = []
        for w in words:
            c = next(ch for ch in chars if abs(ch["x0"] - w["x0"]) < 0.01 and abs(ch["top"] - w["top"]) < 0.01)
            if not c["upright"]:
                continue
            x, y = origin(c)
            xs = [r(ch["matrix"][4] - w["chars"][0]["matrix"][4]) for ch in w["chars"]]   # per-glyph origins
            texts.append({"text": w["text"], "font": FONT[w["fontname"][-2:]], "size": r(w["size"]), "x": x, "y": y,
                          "x1": r(w["x1"]), "xs": xs, "region": region(w)})
        # rotated "Location:" string along the left edge (reads upward)
        rot = sorted((c for c in chars if not c["upright"]), key=lambda c: -c["top"])
        location = "".join(c["text"] for c in rot)
        loc_origin = (r(rot[0]["matrix"][4]), r(H - rot[0]["matrix"][5]))
        loc_size = 5.8                      # same as the footer text; the glyph boxes of rotated text vary

        # ---- annotations of this drawing ----
        circles, welds = [], []
        for o in p.curves:
            if region(o) != "view":
                continue
            w = o["x1"] - o["x0"]
            cx, cy = r((o["x0"] + o["x1"]) / 2), r((o["top"] + o["bottom"]) / 2)
            if not o.get("fill") and len(o["pts"]) == 25 and 12 < w < 16:
                circles.append({"c": [cx, cy], "r": r(w / 2), "lw": r(o["linewidth"])})
            elif not o.get("fill") and len(o["pts"]) == 23 and 12 < w < 14:
                welds.append({"c": [cx, cy], "r": r(w / 2), "lw": r(o["linewidth"])})
        arrows = [[[r(x), r(y)] for x, y in o["pts"][:3]] for o in p.curves if o.get("fill") and len(o["pts"]) == 4]
        ann_lines = []
        for o in p.lines:
            if region(o) != "view":
                continue
            q = o["pts"]
            length = math.hypot(q[1][0] - q[0][0], q[1][1] - q[0][1])
            in_zone = any(inside(o, z) for z in WELD_ZONES + NOTE_ZONES)
            is_leader = o["linewidth"] < 0.5 and length >= LEADER_LINES_MIN and abs(o["top"] - o["bottom"]) + abs(o["x1"] - o["x0"]) > 0
            if in_zone or is_leader:
                if length > 0.2:
                    ann_lines.append([r(q[0][0]), r(q[0][1]), r(q[1][0]), r(q[1][1]), r(o["linewidth"])])
        ann_lines = [list(t) for t in dict.fromkeys(tuple(l) for l in ann_lines)]
        ann_texts = [t for t in texts if t["region"] == "view" and t["font"] == "narrow"]

        # ---- images ----
        ASSETS.mkdir(exist_ok=True)
        with tempfile.TemporaryDirectory() as tmp:
            subprocess.run(["pdfimages", "-j", str(pdf_path), f"{tmp}/img"], check=True)
            full = Image.open(f"{tmp}/img-000.jpg").convert("L")
            bbox = full.point(lambda v: 255 if v < 200 else 0).getbbox()
            sx, sy = W / full.width, H / full.height
            Image.open(f"{tmp}/img-000.jpg").crop(bbox).save(ASSETS / "price_logo.png")
            logo = [r(bbox[0] * sx), r(bbox[1] * sy), r(bbox[2] * sx), r(bbox[3] * sy)]
            shutil.copy(f"{tmp}/img-001.jpg", ASSETS / "photo_blowgun.jpg")
            shutil.copy(f"{tmp}/img-002.jpg", ASSETS / "photo_ejector.jpg")
        photos = [{"file": "photo_blowgun.jpg", "box": [r(p.images[1]["x0"]), r(p.images[1]["top"]), r(p.images[1]["x1"]), r(p.images[1]["bottom"])]},
                  {"file": "photo_ejector.jpg", "box": [r(p.images[2]["x0"]), r(p.images[2]["top"]), r(p.images[2]["x1"]), r(p.images[2]["bottom"])]}]

    template = {"page": [r(W), r(H)], "lines": lines, "curves": curves, "texts": [t for t in texts if t["region"] != "view"],
                "location": {"text": location, "x": loc_origin[0], "y": loc_origin[1], "size": loc_size},
                "logo": {"file": "price_logo.png", "box": logo}}
    annotations = {"balloons": circles, "welds": welds, "arrows": arrows, "lines": ann_lines, "texts": ann_texts, "photos": photos}
    (SRC / "price_template.json").write_text(json.dumps(template, indent=1))
    (SRC / "ie7981a01_annotations.json").write_text(json.dumps(annotations, indent=1))
    print("lines", len(lines), "curves", len(curves), "texts", len(template["texts"]), "| balloons", len(circles), "welds", len(welds),
          "arrows", len(arrows), "ann lines", len(ann_lines), "ann texts", len(ann_texts), "| location", repr(location[:50]), loc_origin, loc_size)


if __name__ == "__main__":
    main(sys.argv[1])
